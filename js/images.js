  /* ── 카드 썸네일 ── */
  function getCardThumb(route) {
    if (route.coverImage) return route.coverImage;
    if (REGION_HERO[route.region]) return REGION_HERO[route.region];
    if (THEME_HERO[route.theme]) return THEME_HERO[route.theme];
    return THEME_HERO['커스텀'];
  }

  /* ── 장소별 이미지 ── */
  function getPlaceImage(place, routeRegion) {
    if (place.image) return place.image;
    // 1. 장소명 전용 이미지
    if (PLACE_IMAGES[place.name]) return PLACE_IMAGES[place.name];
    // 2. 타입별 풀에서 랜덤 선택
    const pool = TYPE_POOL[place.type];
    if (pool?.length) {
      const idx = Math.abs((place.name.charCodeAt(0) || 0)) % pool.length;
      return pool[idx];
    }
    // 3. 지역 대표
    if (REGION_HERO[routeRegion]) return REGION_HERO[routeRegion];
    return THEME_HERO['커스텀'];
  }

  /* ── 갤러리 배열 ── */
  function getGallery(route) {
    const imgs = [];
    imgs.push({ url: getCardThumb(route), caption: route.title, type: 'cover' });
    (route.places || []).forEach(p => {
      imgs.push({ url: getPlaceImage(p, route.region), caption: p.name, type: 'place' });
    });
    return imgs;
  }

  /* ── 그라디언트 폴백 ── */
  function getGradient(id) {
    const idx = (id?.charCodeAt(0) || 0) % GRADIENTS.length;
    return GRADIENTS[idx];
  }

  /* ── XSS-safe 이미지 태그 빌더 ── */
  function _e(s) {
    return String(s ?? '').replace(/[&<>"']/g, c => ({
      '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#x27;'
    }[c]));
  }

  function buildImg(src, alt, classes, gradient) {
    const fb = gradient || GRADIENTS[0];
    return `<img
      src="${_e(src)}"
      alt="${_e(alt)}"
      class="${classes}"
      loading="lazy"
      decoding="async"
      onerror="if(!this.dataset.fb){this.dataset.fb='1';this.src='https://picsum.photos/seed/'+encodeURIComponent(this.alt||'korea')+'/800/600';}else{this.style.display='none';this.parentElement.style.background='${fb}';}"
    />`;
  }

